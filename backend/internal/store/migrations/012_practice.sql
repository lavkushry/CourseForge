CREATE TABLE practice_sessions (
 session_id text PRIMARY KEY CHECK(length(session_id) BETWEEN 1 AND 100),
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 path_id text NOT NULL, step_id text NOT NULL CHECK(length(step_id) BETWEEN 1 AND 100),
 lab_slug text NOT NULL CHECK(lab_slug IN ('python-log-analysis','shell-http-analysis','k8s-resilient-service','sql-customer-revenue','pyspark-order-analytics','docker-hardened-service','ansible-idempotent-web','backend-request-handler')),
 source_snapshot jsonb NOT NULL CHECK(jsonb_typeof(source_snapshot)='object'),
 source_fingerprint text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(session_id,user_id),
 FOREIGN KEY(path_id,user_id) REFERENCES learning_paths(id,user_id) ON DELETE CASCADE
);
CREATE INDEX practice_session_path ON practice_sessions(user_id,path_id,step_id,lab_slug);
CREATE TABLE practice_attempts (
 id text PRIMARY KEY, user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 session_id text NOT NULL, evidence_id text NOT NULL CHECK(length(evidence_id) BETWEEN 1 AND 100),
 passed boolean NOT NULL, checks_passed integer NOT NULL CHECK(checks_passed>=0),
 checks_total integer NOT NULL CHECK(checks_total BETWEEN 1 AND 128 AND checks_passed<=checks_total),
 evidence jsonb NOT NULL CHECK(jsonb_typeof(evidence)='object' AND octet_length(evidence::text)<=65536),
 completed_at timestamptz NOT NULL, accepted_at timestamptz NOT NULL DEFAULT now(),
 accepted_order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 UNIQUE(user_id,evidence_id), FOREIGN KEY(session_id,user_id) REFERENCES practice_sessions(session_id,user_id) ON DELETE CASCADE
);
CREATE INDEX practice_attempt_history ON practice_attempts(user_id,completed_at DESC,id DESC);
CREATE INDEX practice_attempt_session ON practice_attempts(session_id,user_id,completed_at DESC,id DESC);
CREATE TABLE practice_commands (
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 idempotency_key text NOT NULL CHECK(length(idempotency_key) BETWEEN 1 AND 128),
 request_hash text NOT NULL, course_ids text[] NOT NULL,
 source_snapshot jsonb NOT NULL CHECK(jsonb_typeof(source_snapshot)='object'),
 response jsonb NOT NULL CHECK(octet_length(response::text)<=150000),
 status integer NOT NULL CHECK(status BETWEEN 200 AND 299),
 created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(user_id,idempotency_key)
);
CREATE FUNCTION immutable_practice_attempt() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'practice attempts are immutable' USING ERRCODE='23514'; END;
$$;
CREATE TRIGGER practice_attempt_immutable BEFORE UPDATE ON practice_attempts FOR EACH ROW EXECUTE FUNCTION immutable_practice_attempt();
