-- Player QoE telemetry (small validated samples) and per-lesson HLS artifacts.
CREATE TABLE player_telemetry (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  session_id text NOT NULL,
  lesson_id text REFERENCES lessons(id) ON DELETE SET NULL,
  startup_ms integer NOT NULL DEFAULT 0 CHECK (startup_ms >= 0 AND startup_ms < 600000),
  rebuffer_ms integer NOT NULL DEFAULT 0 CHECK (rebuffer_ms >= 0 AND rebuffer_ms < 3600000),
  play_ms integer NOT NULL DEFAULT 0 CHECK (play_ms >= 0 AND play_ms < 86400000),
  errors integer NOT NULL DEFAULT 0 CHECK (errors >= 0 AND errors < 10000),
  bitrate_switches integer NOT NULL DEFAULT 0 CHECK (bitrate_switches >= 0 AND bitrate_switches < 100000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX player_telemetry_created ON player_telemetry(created_at DESC);
CREATE INDEX player_telemetry_user_created ON player_telemetry(user_id, created_at DESC);

CREATE TABLE lesson_hls (
  lesson_id text PRIMARY KEY REFERENCES lessons(id) ON DELETE CASCADE,
  source_path text NOT NULL DEFAULT '',
  source_height integer NOT NULL DEFAULT 0 CHECK (source_height >= 0 AND source_height < 10000),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','ready','failed')),
  master_path text NOT NULL DEFAULT '',
  progressive_path text NOT NULL DEFAULT '',
  poster_path text NOT NULL DEFAULT '',
  error text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX lesson_hls_pending ON lesson_hls(status, updated_at) WHERE status IN ('pending','processing');
