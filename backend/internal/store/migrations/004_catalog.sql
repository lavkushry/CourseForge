CREATE TABLE materials (
 id text PRIMARY KEY, course_id text NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
 lesson_id text, filename text NOT NULL CHECK(length(filename) BETWEEN 1 AND 255),
 title text NOT NULL, material_type text NOT NULL DEFAULT 'Resource',
 scope text NOT NULL DEFAULT 'course' CHECK(scope IN ('course','lesson','section')),
 section_title text NOT NULL DEFAULT '', position double precision NOT NULL DEFAULT 0 CHECK(position>=0 AND position<1e9),
 relative_path text NOT NULL DEFAULT '', claim_name text NOT NULL DEFAULT '', claim_id text NOT NULL DEFAULT '',
 removed boolean NOT NULL DEFAULT false, version bigint NOT NULL DEFAULT 1,
 updated_at timestamptz NOT NULL DEFAULT now(), UNIQUE(course_id,filename),
 FOREIGN KEY(lesson_id,course_id) REFERENCES lessons(id,course_id) ON DELETE CASCADE,
 CHECK(scope<>'lesson' OR lesson_id IS NOT NULL)
);
CREATE INDEX materials_catalog ON materials(course_id,removed,position,id);
CREATE TABLE transcript_chunks (
 id text PRIMARY KEY, lesson_id text NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
 kind text NOT NULL DEFAULT 'transcript', start_seconds double precision NOT NULL CHECK(start_seconds>=0),
 end_seconds double precision NOT NULL CHECK(end_seconds>=start_seconds), text text NOT NULL,
 search_document tsvector GENERATED ALWAYS AS (to_tsvector('simple',text)) STORED
);
CREATE INDEX transcript_search ON transcript_chunks USING gin(search_document);
CREATE INDEX transcript_lesson_time ON transcript_chunks(lesson_id,start_seconds,id);
CREATE TABLE saved_items (
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 item_type text NOT NULL CHECK(item_type IN ('course','lecture')), item_id text NOT NULL,
 course_id text NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
 lesson_id text REFERENCES lessons(id) ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(user_id,item_type,item_id),
 FOREIGN KEY(lesson_id,course_id) REFERENCES lessons(id,course_id) ON DELETE CASCADE,
 CHECK((item_type='course' AND lesson_id IS NULL AND item_id=course_id) OR (item_type='lecture' AND lesson_id IS NOT NULL AND item_id=lesson_id))
);
CREATE TABLE history_cleared (
 user_id text PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, cleared_at timestamptz NOT NULL
);
CREATE TABLE watch_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 lesson_id text NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,
 course_id text NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
 position double precision NOT NULL DEFAULT 0 CHECK(position>=0 AND position<1e9),
 duration_seconds double precision NOT NULL DEFAULT 0 CHECK(duration_seconds>=0 AND duration_seconds<1e9),
 completed boolean NOT NULL DEFAULT false, watched_at timestamptz NOT NULL
 ,FOREIGN KEY(lesson_id,course_id) REFERENCES lessons(id,course_id) ON DELETE CASCADE
);
CREATE INDEX watch_history_owner ON watch_history(user_id,watched_at DESC,lesson_id);
CREATE INDEX progress_history ON progress(user_id,updated_at DESC,lesson_id);
CREATE TABLE streaming_analytics (
 day date NOT NULL, event_type text NOT NULL CHECK(event_type IN ('row_click','search_query','search_click','failover','up_next_accepted','up_next_declined')),
 event_name text NOT NULL CHECK(length(event_name) BETWEEN 1 AND 200),
 count bigint NOT NULL DEFAULT 0 CHECK(count>=0), PRIMARY KEY(day,event_type,event_name)
);
